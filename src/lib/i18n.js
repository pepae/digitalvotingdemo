const DICT = { fr: FR, en: EN };
export function t(key, vars) {
  const st = getState();
  const lang = st.settings.lang || 'fr';
  const d = DICT[lang] || FR;
  let s = (st.settings.falc && d[key + '.falc']) || d[key] || FR[key] || key;
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}
export const lang = () => getState().settings.lang || 'fr';

